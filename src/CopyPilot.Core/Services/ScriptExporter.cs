using System.Text;

namespace CopyPilot.Core.Services;

/// <summary>Exports a command as a reusable .ps1 or .cmd script (e.g. for Task Scheduler).</summary>
public static class ScriptExporter
{
    private const string Header = "Generated by CopyPilot (created by Arnold Kolkman)";

    public static string ToPowerShell(string exe, CommandPlan plan, IReadOnlyDictionary<string, string> environment)
    {
        static string Q(string s) => "'" + s.Replace("'", "''") + "'";

        var sb = new StringBuilder();
        sb.AppendLine("# " + Header);
        sb.AppendLine("$ErrorActionPreference = 'Stop'");
        foreach (var (k, v) in environment) sb.AppendLine($"$env:{k} = {Q(v)}");

        if (plan.StdinFile != null || plan.StdoutFile != null)
        {
            var args = string.Join(" ", plan.Arguments.Select(a => CommandBuilder.Quote(a)));
            sb.Append($"$p = Start-Process -FilePath {Q(exe)} -ArgumentList {Q(args)} -NoNewWindow -Wait -PassThru");
            if (plan.StdinFile != null) sb.Append($" -RedirectStandardInput {Q(plan.StdinFile)}");
            if (plan.StdoutFile != null) sb.Append($" -RedirectStandardOutput {Q(plan.StdoutFile)}");
            sb.AppendLine();
            sb.AppendLine("exit $p.ExitCode");
        }
        else
        {
            sb.AppendLine("& " + Q(exe) + " " + string.Join(" ", plan.Arguments.Select(Q)));
            sb.AppendLine("exit $LASTEXITCODE");
        }

        return sb.ToString();
    }

    public static string ToCmd(string exe, CommandPlan plan, IReadOnlyDictionary<string, string> environment)
    {
        // In batch files '%' must be doubled (SAS tokens contain %xx escapes).
        static string E(string s) => s.Replace("%", "%%");

        var sb = new StringBuilder();
        sb.AppendLine("@echo off");
        sb.AppendLine("rem " + Header);
        sb.AppendLine("setlocal");
        foreach (var (k, v) in environment) sb.AppendLine($"set \"{k}={E(v)}\"");
        sb.AppendLine(E(plan.ToUnmaskedString(exe)));
        sb.AppendLine("exit /b %ERRORLEVEL%");
        return sb.ToString();
    }
}
